			hCosThetaK_Y->Fill(costhetakY2);//cumulative
			hExEt_Y2->Fill(E_xY2/E_Txy_Y2);//y2
			hExEt_Y->Fill(E_xY2/E_Txy_Y2);//cumulative
			hEyEt_Y2->Fill(E_yY2/E_Txy_Y2);//y2
			hEyEt_Y->Fill(E_yY2/E_Txy_Y2);//cumulative
