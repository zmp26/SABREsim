			TVector3 betaCMtoIntermediateCM = -intermediateCM.BoostVector();

			cosThetaH_a1 = -666.;
			cosThetaH_a2 = -666.;
			thetaH_a1_deg = -666.;
			thetaH_a2_deg = -666.;


