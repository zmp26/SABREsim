	double eStep=0.02;//updated from 0.1 (100keV) to 0.02 (20 keV)
	int nSlices = static_cast<int>((eMax-eMin)/eStep);
	std::vector<TH2D*> vDalitz(nSlices, nullptr);
	std::vector<TH2D*> vCatania(nSlices, nullptr);
